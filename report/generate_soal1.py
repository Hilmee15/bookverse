def safe_keep(elements):
    total = 0
    for el in elements:
        _, h = el.wrap(AVAIL_W, PAGE_H)
        total += h
    if total <= MAX_KEEP:
        return [KeepTogether(elements)]
    if len(elements) >= 2:
        return [KeepTogether(elements[:2])] + list(elements[2:])
    return list(elements)


def h1(story, text):
    story.append(CondPageBreak(H1_ORPHAN))
    block = [
        Paragraph("<b>%s</b>" % text, S["h1"]),
        HRFlowable(width="100%", thickness=1.1, color=ACCENT, spaceBefore=3, spaceAfter=9),
    ]
    story.extend(safe_keep(block))


def h2(story, text):
    story.append(CondPageBreak(H1_ORPHAN * 0.6))
    story.append(Paragraph("<b>%s</b>" % text, S["h2"]))


def make_table(header, rows, ratios, aligns=None, font=9, repeat=True):
    widths = [r * AVAIL_W for r in ratios]
    assert abs(sum(widths) - AVAIL_W) < 2.0, "column widths exceed available width"
    data = [[Paragraph("<b>%s</b>" % c, S["th"]) for c in header]]
    for row in rows:
        cells = []
        for i, c in enumerate(row):
            style = S["td"] if not aligns else (S["tdC"] if aligns[i] == "c" else
                                               (S["tdB"] if aligns[i] == "b" else S["td"]))
            if font != 9:
                style = ParagraphStyle("tmp%d" % font, parent=style, fontSize=font,
                                       leading=font + 3)
            cells.append(Paragraph(c, style))
        data.append(cells)
    t = Table(data, colWidths=widths, hAlign="CENTER", repeatRows=1 if repeat else 0)
    style_cmds = [
        ("BACKGROUND", (0, 0), (-1, 0), HEADER_FILL),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]
    for r in range(1, len(data)):
        style_cmds.append(("BACKGROUND", (0, r), (-1, r),
                           colors.white if r % 2 == 1 else TABLE_STRIPE))
    t.setStyle(TableStyle(style_cmds))
    return t


